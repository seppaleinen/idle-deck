// TestTierMeta asserts that TierMetaTable values match the D37 literals
// (M4, M3, L7): budgets are 5000/100000/20000/50000 for P0/P1/P2/P3
// and timeouts are 900/10800/3600/1800s for P0/P1/P2/P3.
func TestTierMeta(t *testing.T) {
	expectedTimeouts := map[TaskTier]int{
		TierP0: 1800,
		TierP1: 900,
		TierP2: 10800,
		TierP3: 3600,
	}
	expectedBudgets := map[TaskTier]int{
		TierP0: 50000,
		TierP1: 5000,
		TierP2: 100000,
		TierP3: 20000,
	}

	for tier, meta := range TierMetaTable {
		expTimeout, ok := expectedTimeouts[tier]
		if !ok {
			t.Fatalf("no expected timeout for tier %s", tier)
		}
		if meta.DefaultTimeout != expTimeout {
			t.Errorf("TierMeta[%s].DefaultTimeout = %d, want %d", tier, meta.DefaultTimeout, expTimeout)
		}

		expBudget, ok := expectedBudgets[tier]
		if !ok {
			t.Fatalf("no expected budget for tier %s", tier)
		}
		if meta.DefaultBudget != expBudget {
			t.Errorf("TierMeta[%s].DefaultBudget = %d, want %d", tier, meta.DefaultBudget, expBudget)
		}
	}
}

// TestTierRank asserts that TierRank returns correct values.
func TestTierRank(t *testing.T) {
	expectedRanks := map[TaskTier]int{
		TierP0: 0,
		TierP1: 1,
		TierP2: 2,
		TierP3: 3,
	}

	for tier := range expectedRanks {
		expectedRank := expectedRanks[tier]
		if TierRank(tier) != expectedRank {
			t.Errorf("TierRank(%s) = %d, want %d", tier, TierRank(tier), expectedRank)
		}
	}
}

// TestTierOrderingSQL asserts that the SQL CASE expression generated by
// TierOrderingSQL matches the TierMetaTable rank order.
func TestTierOrderingSQL(t *testing.T) {
	sql := TierOrderingSQL()
	expected := "CASE tier WHEN 'P0' THEN 0 WHEN 'P1' THEN 1 WHEN 'P2' THEN 2 WHEN 'P3' THEN 3 ELSE 99 END"
	if sql != expected {
		t.Errorf("TierOrderingSQL() = %q, want %q", sql, expected)
	}
}

